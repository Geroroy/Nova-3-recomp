"""Write the generated C sources for a recompiled module."""
from __future__ import annotations

import os

from .analysis import Analyzer
from .disasm import THUMB
from .elf import ElfImage
from .lifter import Lifter


def cname_for(addr: int, base: int) -> str:
    return f"f_{(addr + base) & 0xFFFFFFFF:08x}"


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(img: ElfImage, an: Analyzer, outdir: str, base: int, funcs_per_file: int = 400,
         module: str = "mod", log=print) -> dict:
    os.makedirs(outdir, exist_ok=True)
    fns = sorted(an.functions.values(), key=lambda f: f.addr)
    names = {f.addr: cname_for(f.addr, base) for f in fns}
    lifter = Lifter(an, base, names, module)

    # header with prototypes
    with open(os.path.join(outdir, f"{module}_funcs.h"), "w") as h:
        h.write("#pragma once\n#include \"recomp.h\"\n\n")
        h.write(f"extern guest_fn {module}_import_fns[];\n\n")
        for f in fns:
            h.write(f"void {names[f.addr]}(CPU *c);\n")

    files = []
    ninsn = 0
    for k in range(0, len(fns), funcs_per_file):
        chunk = fns[k:k + funcs_per_file]
        fname = f"{module}_funcs_{k // funcs_per_file:04d}.c"
        files.append(fname)
        with open(os.path.join(outdir, fname), "w") as out:
            out.write(f"/* generated by nova3recomp from {os.path.basename(img.path)} -- do not edit */\n")
            out.write(f"#include \"{module}_funcs.h\"\n")
            out.write("#pragma GCC diagnostic ignored \"-Wunused-label\"\n")
            out.write("#pragma clang diagnostic ignored \"-Wunused-label\"\n\n")
            for f in chunk:
                if f.name:
                    out.write(f"/* {f.name} */\n")
                out.write(lifter.lift_function(f, names[f.addr]))
                out.write("\n")
                ninsn += len(f.insns)

    # module description: function table, segments, relocations, imports, exports
    with open(os.path.join(outdir, f"{module}_module.c"), "w") as out:
        out.write(f"/* generated by nova3recomp -- do not edit */\n#include \"{module}_funcs.h\"\n")
        out.write("#include \"module.h\"\n\n")
        out.write(f"static const FuncEntry funcs[] = {{\n")
        for f in fns:
            out.write(f"    {{0x{(f.addr + base) & 0xFFFFFFFF:08x}u, {names[f.addr]}}},\n")
        out.write("};\n\n")
        out.write("static const SegmentInfo segments[] = {\n")
        for s in img.segments:
            out.write(f"    {{0x{s.vaddr:x}u, 0x{s.memsz:x}u, 0x{s.offset:x}u, 0x{s.filesz:x}u, {s.flags}}},\n")
        out.write("};\n\n")
        out.write("static const RelocInfo relocs[] = {\n")
        for r in img.relocs:
            imp = -1
            symval = 0
            if r.sym is not None:
                if r.sym.defined:
                    symval = r.sym.value
                elif r.sym.name in img.import_by_name:
                    imp = img.import_by_name[r.sym.name].id
            out.write(f"    {{0x{r.offset:x}u, {r.type}, {imp}, 0x{symval:x}u, {r.addend}}},\n")
        out.write("    {0, 0, 0, 0, 0}\n};\n\n")
        out.write("static const ImportInfo imports[] = {\n")
        for imp in img.imports:
            out.write(f"    {{{c_string(imp.name)}, {int(imp.is_func)}}},\n")
        out.write("    {0, 0}\n};\n\n")
        exports = sorted({(s.name, s.value, s.type == "STT_FUNC", s.size) for s in img.dynsyms
                          if s.defined and s.name})
        out.write("static const ExportInfo exports[] = {\n")
        for n, v, isf, sz in exports:
            out.write(f"    {{{c_string(n)}, 0x{v:x}u, {int(isf)}, {sz}}},\n")
        out.write("    {0, 0, 0, 0}\n};\n\n")
        init = list(img.init_array)
        out.write("static const uint32_t init_array[] = {")
        out.write(", ".join(f"0x{a:x}u" for a in init) or "0")
        out.write("};\n")
        out.write(f"guest_fn {module}_import_fns[{max(1, len(img.imports))}];\n\n")
        out.write("const ModuleInfo " + module + "_module = {\n")
        out.write(f"    {c_string(module)}, {c_string(os.path.basename(img.path))}, {c_string(img.sha1)},\n")
        out.write(f"    0x{base:08x}u, 0x{img.min_vaddr:x}u, 0x{img.max_vaddr:x}u,\n")
        out.write(f"    funcs, {len(fns)},\n")
        out.write(f"    segments, {len(img.segments)},\n")
        out.write(f"    relocs, {len(img.relocs)},\n")
        out.write(f"    imports, {len(img.imports)},\n")
        out.write(f"    exports, {len(exports)},\n")
        out.write(f"    init_array, {len(init)},\n")
        out.write(f"    0x{(img.dt_init or 0):x}u,\n")
        out.write(f"    {module}_import_fns,\n")
        out.write("};\n")
    files.append(f"{module}_module.c")

    with open(os.path.join(outdir, f"{module}_sources.cmake"), "w") as out:
        out.write(f"set({module.upper()}_GENERATED_SOURCES\n")
        for f in files:
            out.write(f"    ${{CMAKE_CURRENT_LIST_DIR}}/{f}\n")
        out.write(")\n")

    stats = {
        "functions": len(fns),
        "instructions": ninsn,
        "imports": len(img.imports),
        "unsupported": dict(lifter.unsupported.most_common()),
        "unsupported_examples": lifter.unsupported_where,
        **an.stats,
    }
    with open(os.path.join(outdir, f"{module}_report.md"), "w") as out:
        out.write(f"# Recompilation report: {os.path.basename(img.path)}\n\n")
        out.write(f"- SHA-1: `{img.sha1}`\n")
        for k in ("functions", "instructions", "imports", "ijump_tables", "ijump_unresolved", "undecodable"):
            out.write(f"- {k}: {stats[k]}\n")
        out.write("\n## Unsupported instructions\n\n")
        if not lifter.unsupported:
            out.write("None.\n")
        else:
            out.write("| mnemonic | count | first occurrence |\n|---|---|---|\n")
            for m, n in lifter.unsupported.most_common():
                out.write(f"| {m} | {n} | `{lifter.unsupported_where[m]}` |\n")
        out.write("\n## Imports\n\n")
        for imp in img.imports:
            out.write(f"- `{imp.name}`{' (data)' if not imp.is_func else ''}\n")
    return stats
